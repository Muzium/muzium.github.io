const svgCache = new Map();

export async function inlineSVG(host, path, invert = false) {
  if (!host) return;
  if (!svgCache.has(path)) {
    svgCache.set(path, fetch(asset(path))
      .then((r) => (r.ok ? r.text() : Promise.reject(new Error(String(r.status)))))
      .then((t) => recolorSVG(t, invert))
      .catch(() => ''));
  }
  const markup = await svgCache.get(path);
  if (markup) host.innerHTML = markup;
}

/** 去掉硬编码实色填充（黑/白），改用 currentColor；并让 svg 自适应容器高度 */
export function recolorSVG(src, invert = false) {
  // 黑或白都视为「单色填充」，统一换成 currentColor，由容器 color 决定明暗
  const SOLID = '(?:black|white|#000|#000000|#fff|#ffffff|rgb\\(\\s*0\\s*,\\s*0\\s*,\\s*0\\s*\\)|rgb\\(\\s*255\\s*,\\s*255\\s*,\\s*255\\s*\\))';
  return src
    .replace(/<\?xml[\s\S]*?\?>/g, '')
    .replace(/<!--[\s\S]*?-->/g, '')
    .replace(new RegExp(`\\sfill=(["'])(${SOLID})\\1`, 'gi'), ' fill="currentColor"')
    .replace(new RegExp(`fill\\s*:\\s*(${SOLID})\\s*;?`, 'gi'), 'fill:currentColor;')
    .replace(/<svg\b([^>]*)>/i, (m, attrs) => {
      // 必须先删掉根节点上原有的 width/height/fill，
      // 否则重复属性里「先出现的那个」生效（源文件是 fill="none"，会导致整个图形不可见）
      const cleaned = attrs
        .replace(/\swidth\s*=\s*(["'])[^"']*\1/gi, '')
        .replace(/\sheight\s*=\s*(["'])[^"']*\1/gi, '')
        .replace(/\sfill\s*=\s*(["'])[^"']*\1/gi, '');
      const styleAttr = invert ? ' style="color:var(--fg)"' : '';
      return `<svg${cleaned} height="100%" fill="currentColor" focusable="false" aria-hidden="true"${styleAttr}>`;
    })
    .trim();
}

/** 让 position:sticky 元素在吸顶时得到 .stuck */
export function observeStuck(scope = document) {
  const bars = scope.querySelectorAll('.engine-sticky');
  if (!bars.length || !('IntersectionObserver' in window)) return;
  const top = parseInt(getComputedStyle(document.documentElement).getPropertyValue('--topbar-h')) || 64;
  bars.forEach((bar) => {
    const sentinel = document.createElement('div');
    sentinel.style.cssText = 'position:absolute;height:1px;width:1px;';
    bar.parentElement.style.position = 'relative';
    bar.parentElement.prepend(sentinel);
    new IntersectionObserver(
      ([e]) => bar.classList.toggle('stuck', !e.isIntersecting),
      { rootMargin: `-${top + 1}px 0px 0px 0px`, threshold: 0 }
    ).observe(sentinel);
  });
}

