const THEME_KEY = 'muzium.theme';

export function getTheme() {
  return document.documentElement.dataset.theme === 'light' ? 'light' : 'dark';
}

export function setTheme(t, animate = true) {
  const root = document.documentElement;
  if (animate) {
    root.classList.add('theme-anim');
    clearTimeout(setTheme._t);
    setTheme._t = setTimeout(() => root.classList.remove('theme-anim'), 500);
  }
  root.dataset.theme = t;
  try { localStorage.setItem(THEME_KEY, t); } catch (e) { /* 隐私模式 */ }
  document.dispatchEvent(new CustomEvent('theme:change', { detail: { theme: t } }));
}

export function toggleTheme() {
  setTheme(getTheme() === 'light' ? 'dark' : 'light');
}

