/** 转义 HTML，防止数据里的尖括号破坏结构 */
export const esc = (s = '') =>
  String(s).replace(/[&<>"']/g, (c) =>
    ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]));

/** 站内资源路径：把 /assets/... 解析为相对于 site/ 的上一级 */
export const asset = (p = '') => {
  if (!p) return '';
  if (/^(https?:)?\/\//.test(p) || p.startsWith('data:')) return p;
  return '..' + (p.startsWith('/') ? p : '/' + p);
};

export const fmtTime = (s) => {
  if (!isFinite(s) || s < 0) s = 0;
  const m = Math.floor(s / 60);
  const r = Math.floor(s % 60);
  return `${m}:${String(r).padStart(2, '0')}`;
};

export const el = (html) => {
  const t = document.createElement('template');
  t.innerHTML = html.trim();
  return t.content.firstElementChild;
};

export const clamp = (v, a, b) => Math.min(b, Math.max(a, v));

/** 把角色代表色写入 CSS 变量；无值则回落到默认金色 */
export function applyAccent(primary, secondary) {
  const root = document.documentElement;
  root.style.setProperty('--accent', primary || '#c9a227');
  root.style.setProperty('--accent-2', secondary || '#6a7fbf');
  root.style.setProperty('--accent-ink', pickInk(primary || '#c9a227'));
}

/** 依据背景色亮度选择前景黑/白，保证对比度 */
export function pickInk(hex) {
  const m = /^#?([a-f\d]{2})([a-f\d]{2})([a-f\d]{2})$/i.exec(hex || '');
  if (!m) return '#0b0b0d';
  const [r, g, b] = [1, 2, 3].map((i) => parseInt(m[i], 16) / 255);
  const lin = (c) => (c <= 0.03928 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4);
  const L = 0.2126 * lin(r) + 0.7152 * lin(g) + 0.0722 * lin(b);
  return L > 0.45 ? '#0b0b0d' : '#ffffff';
}

/** 滚动进入视口时加 .in；并加多重保底，杜绝「透明占位却可点击」的空白 */
export function observeReveal(scope = document) {
  const items = scope.querySelectorAll('.reveal:not(.in)');
  if (!items.length) return;
  if (!('IntersectionObserver' in window)) {
    items.forEach((n) => n.classList.add('in'));
    return;
  }
  const io = new IntersectionObserver(
    (entries) => {
      entries.forEach((e) => {
        if (e.isIntersecting) {
          e.target.classList.add('in');
          io.unobserve(e.target);
        }
      });
    },
    { rootMargin: '0px 0px -8% 0px', threshold: 0.01 }
  );
  const vh = window.innerHeight || document.documentElement.clientHeight;
  const isVisible = (n) => {
    const r = n.getBoundingClientRect();
    return r.top < vh && r.bottom > 0;
  };
  items.forEach((n) => {
    io.observe(n);
    if (isVisible(n)) n.classList.add('in'); // 首屏可见的立即显示
  });
  // 保底：多次复检，仅把「已在视口内却仍未显示」的元素点亮，
  // 绝不强行显示视口外的元素，从而保留滚动入场、同时杜绝永久透明空白
  const sweep = () => scope.querySelectorAll('.reveal:not(.in)').forEach((n) => {
    if (isVisible(n)) n.classList.add('in');
  });
  requestAnimationFrame(sweep);
  setTimeout(sweep, 300);
  setTimeout(sweep, 800);
  window.addEventListener('scroll', sweep, { passive: true });
  window.addEventListener('resize', sweep);
}

